#!/bin/sh
# Regenerate Formula/arc.rb for a release. The formula is a generated artifact; this template is
# its one source — edit here, never the .rb. Invoked by arclite's release workflow (its `tap` job,
# with checksums read from the release's SHA256SUMS), or by hand:
#
#   ./bump.sh v0.1.12 <sha_macos_aarch64> <sha_macos_x86_64> <sha_linux_x86_64> <sha_linux_aarch64>
set -eu

[ $# -eq 5 ] || {
    echo "usage: ./bump.sh <tag> <sha_macos_aarch64> <sha_macos_x86_64> <sha_linux_x86_64> <sha_linux_aarch64>" >&2
    exit 1
}
TAG=$1
MACOS_ARM=$2
MACOS_INTEL=$3
LINUX_INTEL=$4
LINUX_ARM=$5

case "$TAG" in
v*) ;;
*)
    echo "bump: tag must be v-prefixed, got '$TAG'" >&2
    exit 1
    ;;
esac
for sha in "$MACOS_ARM" "$MACOS_INTEL" "$LINUX_INTEL" "$LINUX_ARM"; do
    case "$sha" in
    *[!0-9a-f]* | "")
        echo "bump: '$sha' is not a lowercase sha256" >&2
        exit 1
        ;;
    esac
    [ "${#sha}" -eq 64 ] || {
        echo "bump: '$sha' is not 64 hex chars" >&2
        exit 1
    }
done
VERSION=${TAG#v}
BASE="https://github.com/euhedron/arclite/releases/download/$TAG"

cat >Formula/arc.rb <<EOF
# GENERATED by ./bump.sh — edit the template there, never this file.
class Arc < Formula
  desc "Agent-first CLI for AI-powered cross-repo code intelligence and auditing"
  homepage "https://github.com/euhedron/arclite"
  version "$VERSION"
  license "MIT"

  on_macos do
    on_arm do
      url "$BASE/arc-$TAG-macos-aarch64"
      sha256 "$MACOS_ARM"
    end
    on_intel do
      url "$BASE/arc-$TAG-macos-x86_64"
      sha256 "$MACOS_INTEL"
    end
  end
  on_linux do
    on_intel do
      url "$BASE/arc-$TAG-linux-x86_64"
      sha256 "$LINUX_INTEL"
    end
    on_arm do
      url "$BASE/arc-$TAG-linux-aarch64"
      sha256 "$LINUX_ARM"
    end
  end

  def install
    bin.install Dir["arc-v*"].first => "arc"
  end

  livecheck do
    url :homepage
    strategy :github_latest
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/arc --version")
  end
end
EOF
echo "Formula/arc.rb -> arc $VERSION"
